/// First-write-wins model of a batch: for each dedup key, the message that
/// storage must keep (the first occurrence ever inserted).
pub fn first_write_model<'a>(
    batch: impl IntoIterator<Item = &'a NewMessage>,
) -> HashMap<(String, String), &'a NewMessage> {
    let mut model = HashMap::new();
    for msg in batch {
        model
            .entry((msg.source.clone(), msg.external_id.clone()))
            .or_insert_with(|| msg);
    }
    model
}

/// Same message with visibly different content — used to prove a re-insert
/// never overwrites the stored row.
pub fn mutate(msg: &NewMessage) -> NewMessage {
    let mut m = msg.clone();
    m.body = format!("mutated-variant {}", m.body);
    m.author = format!("mutated-variant {}", m.author);
    m
}

/// A [`Source`] serving a fixed batch, optionally reporting parse failures.
pub struct FixtureSource {
    name: String,
    messages: Vec<NewMessage>,
    failed: u64,
}

impl FixtureSource {
    pub fn new(name: &str, messages: Vec<NewMessage>, failed: u64) -> Self {
        Self {
            name: name.to_string(),
            messages,
            failed,
        }
    }
}

impl Source for FixtureSource {
    fn name(&self) -> &str {
        &self.name
    }

    fn collect(&self) -> vault_core::Result<Collected> {
        Ok(Collected {
            messages: self.messages.clone(),
            failed: self.failed,
        })
    }
}
