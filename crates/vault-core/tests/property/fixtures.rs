pub fn quoted_term(term: &str) -> String {
    format!("\"{term}\"")
}

pub fn quoted_prefix(prefix: &str) -> String {
    format!("\"{prefix}\"*")
}

pub fn quoted_phrase(a: &str, b: &str) -> String {
    format!("\"{a} {b}\"")
}

// --------------------------------------------------------------------------
// Deterministic generator (SplitMix64)
// --------------------------------------------------------------------------

/// Minimal deterministic PRNG so golden batches reproduce exactly from a
/// bare `u64` seed with no external machinery.
pub struct Rng(u64);

impl Rng {
    pub fn new(seed: u64) -> Self {
        Rng(seed)
    }

    pub fn next_u64(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9E37_79B9_7F4A_7C15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        z ^ (z >> 31)
    }

    pub fn pick<'a, T>(&mut self, items: &'a [T]) -> &'a T {
        &items[(self.next_u64() % items.len() as u64) as usize]
    }

    /// Uniform value in `lo..=hi`.
    pub fn range(&mut self, lo: u64, hi: u64) -> u64 {
        lo + self.next_u64() % (hi - lo + 1)
    }
}

/// Deterministically generate `len` messages from `seed`, with forced
/// dedup-key collisions (external ids repeat) so every golden batch
/// exercises the idempotence paths. Same seed → same batch, always.
pub fn golden_batch(seed: u64, len: usize) -> Vec<NewMessage> {
    let mut rng = Rng::new(seed);
    let id_space = (len as u64 / 3).max(1);
    (0..len)
        .map(|_| {
            let source = (*rng.pick(SOURCES)).to_string();
            let external_id = format!("msg-{}", rng.range(0, id_space));
            NewMessage::new(
                source,
                external_id,
                golden_text(&mut rng, 0..=2),
                golden_sent_at(&mut rng),
                golden_text(&mut rng, 0..=6),
            )
        })
        .collect()
}

fn golden_text(rng: &mut Rng, tokens: std::ops::RangeInclusive<u64>) -> String {
    let count = rng.range(*tokens.start(), *tokens.end());
    let mut text = golden_word(rng);
    for _ in 0..count {
        let sep = *rng.pick(&[" ", ", ", ". ", " - ", "_", "\n", ""]);
        text = format!("{text}{sep}{}", golden_word(rng));
    }
    text
}

fn golden_word(rng: &mut Rng) -> String {
    let roll = rng.range(0, 9);
    if roll < 5 {
        (*rng.pick(ASCII_WORDS)).to_string()
    } else if roll < 7 {
        rng.pick(ACCENT_WORDS).0.to_string()
    } else if roll < 8 {
        (*rng.pick(CYRILLIC_WORDS)).to_string()
    } else {
        (*rng.pick(CJK_WORDS)).to_string()
    }
}

fn golden_sent_at(rng: &mut Rng) -> String {
    format!(
        "{:04}-{:02}-{:02}T{:02}:{:02}:{:02}Z",
        rng.range(2020, 2029),
        rng.range(1, 12),
        rng.range(1, 28),
        rng.range(0, 23),
        rng.range(0, 59),
        rng.range(0, 59)
    )
}

// --------------------------------------------------------------------------
// proptest strategies
// --------------------------------------------------------------------------

/// One vocabulary word in its literal spelling.
fn literal_word() -> impl Strategy<Value = String> {
    prop_oneof![
        4 => select(ASCII_WORDS).prop_map(String::from),
        2 => select(ACCENT_WORDS).prop_map(|(w, _)| w.to_string()),
        2 => (select(CYRILLIC_WORDS), any::<u64>())
            .prop_map(|(w, mask)| case_fold_cyrillic(w, mask)),
        1 => select(CJK_WORDS).prop_map(String::from),
    ]
}

/// Random per-character case: `unicode61` folds Cyrillic case-insensitively,
/// so documents may carry mixed case.
fn case_fold_cyrillic(word: &str, mask: u64) -> String {
    word.chars()
        .enumerate()
        .map(|(i, c)| {
            if (mask >> (i % 64)) & 1 == 1 {
                c.to_uppercase().next().unwrap_or(c)
            } else {
                c
            }
        })
        .collect()
}

/// Token separators between generated words. The empty separator fuses two
/// words into one longer token (both sides tokenize the fused string).
fn separator() -> impl Strategy<Value = &'static str> {
    select(&[" ", ", ", ". ", " - ", "_", "\n", ""])
}

/// A body/author field built from vocabulary words joined by random
/// separators.
pub fn field_text(min: usize, max: usize) -> impl Strategy<Value = String> {
    collection::vec((literal_word(), separator()), min..=max).prop_map(|parts| {
        parts
            .into_iter()
            .map(|(word, sep)| format!("{word}{sep}"))
            .collect()
    })
}

pub fn sent_at() -> impl Strategy<Value = String> {
    (
        2020u32..=2029,
        1u32..=12,
        1u32..=28,
        0u32..=23,
        0u32..=59,
        0u32..=59,
    )
        .prop_map(|(y, mo, d, h, mi, s)| format!("{y:04}-{mo:02}-{d:02}T{h:02}:{mi:02}:{s:02}Z"))
}

/// External ids drawn from a small pool (so duplicates occur naturally)
/// plus hostile spellings — the dedup key is an opaque string.
pub fn external_id() -> impl Strategy<Value = String> {
    prop_oneof![
        6 => (0u16..24).prop_map(|i| format!("msg-{i}")),
        1 => select(WEIRD_IDS).prop_map(String::from),
    ]
}

/// A fully random message: random dedup key, author, timestamp, and body.
pub fn message() -> impl Strategy<Value = NewMessage> {
    (
        select(SOURCES),
        external_id(),
        field_text(0, 2),
        sent_at(),
        field_text(0, 8),
    )
        .prop_map(|(source, external_id, author, sent_at, body)| {
            NewMessage::new(source, external_id, author, sent_at, body)
        })
}

/// A random batch of messages, `0..=max` long.
pub fn batch(max: usize) -> impl Strategy<Value = Vec<NewMessage>> {
    collection::vec(message(), 0..=max)
}

