//! Random-message fixture builder and an independent FTS5 `unicode61`
//! oracle.
//!
//! Generation draws from a small fixed vocabulary per script so that the
//! oracle below can recompute, from first principles, exactly which
//! documents each MATCH query must return. The vocabulary characters cover
//! the tokenizer behaviours the contract cares about; the oracle rules were
//! verified against the bundled SQLite once and are kept in sync with the
//! schema in `vault_core::storage` (FTS5 defaults: `unicode61` tokenizer,
//! `remove_diacritics` on).

use std::collections::HashMap;

use proptest::collection;
use proptest::prelude::*;
use proptest::sample::select;
use vault_core::ingest::{Collected, Source};
use vault_core::message::NewMessage;

// --------------------------------------------------------------------------
// Vocabulary
// --------------------------------------------------------------------------

/// Plain ASCII words (lowercase; case variants are generated by re-casing).
pub const ASCII_WORDS: &[&str] = &[
    "vault", "report", "archive", "search", "hello", "world", "alpha", "beta", "gamma", "rev7",
    "2026",
];

/// Latin words with diacritics that `unicode61` folds to their ASCII base
/// form, paired with that base form. (Characters without a canonical
/// decomposition — `đ`, `ł`, `ß` — are deliberately NOT used: the tokenizer
/// keeps them distinct.)
pub const ACCENT_WORDS: &[(&str, &str)] = &[
    ("café", "cafe"),
    ("čvarci", "cvarci"),
    ("šamar", "samar"),
    ("žirafa", "zirafa"),
    ("ćevapi", "cevapi"),
    ("trešnja", "tresnja"),
    ("müde", "mude"),
    ("schön", "schon"),
];

/// Cyrillic words (generated with random per-character case; `unicode61`
/// case-folds Cyrillic just like ASCII).
pub const CYRILLIC_WORDS: &[&str] = &["греј", "архив", "претрага", "извештај", "свет", "зима"];

/// CJK runs: every CJK codepoint is a token character, so a whole run
/// forms ONE token — only exact-run and prefix matches, never substrings.
pub const CJK_WORDS: &[&str] = &["邮件", "档案库", "搜索", "测试", "你好世界"];

/// Dedup namespaces messages are generated from.
pub const SOURCES: &[&str] = &["mbox", "whatsapp", "telegram", "demo"];

/// Opaque dedup-key spellings that must never confuse storage.
const WEIRD_IDS: &[&str] = &[
    "",
    "\"quoted\"",
    "нормално",
    "id with space",
    "🦀",
    "a'b\"c",
];

// --------------------------------------------------------------------------
// unicode61 oracle
// --------------------------------------------------------------------------

/// Map a lowercase accented Latin char to its ASCII base (the subset the
/// bundled tokenizer folds with `remove_diacritics`).
fn base_of(c: char) -> Option<char> {
    Some(match c {
        'á' | 'à' | 'â' | 'ä' | 'ã' | 'å' | 'ā' | 'ą' => 'a',
        'é' | 'è' | 'ê' | 'ë' | 'ē' | 'ę' => 'e',
        'í' | 'ì' | 'î' | 'ï' | 'ī' => 'i',
        'ó' | 'ò' | 'ô' | 'ö' | 'õ' | 'ō' | 'ő' => 'o',
        'ú' | 'ù' | 'û' | 'ü' | 'ū' | 'ů' | 'ű' => 'u',
        'ý' => 'y',
        'ć' | 'č' | 'ç' => 'c',
        'ģ' => 'g',
        'ķ' => 'k',
        'ļ' => 'l',
        'ņ' => 'n',
        'ŗ' => 'r',
        'š' => 's',
        'ž' => 'z',
        _ => return None,
    })
}

/// `unicode61` normalization of one character: diacritic removal plus
/// simple lowercasing (ASCII and Cyrillic cover everything generated).
/// Uppercase accented Latin folds directly to the base form (Ö → o), so
/// lowercase first, then strip the diacritic.
pub fn fold_char(c: char) -> char {
    // Latin-1 Supplement + Latin Extended-A: lowercase, then remove the
    // diacritic (characters without a decomposition — đ, ł, ø, æ — stay).
    if ('\u{00C0}'..='\u{017F}').contains(&c) {
        let lower = c.to_lowercase().next().unwrap_or(c);
        return base_of(lower).unwrap_or(lower);
    }
    match c {
        'A'..='Z' => char::from_u32(c as u32 + 0x20).unwrap_or(c),
        // А..Я → а..я
        '\u{0410}'..='\u{042F}' => char::from_u32(c as u32 + 0x20).unwrap_or(c),
        // Ѐ..Џ → ѐ..џ (Ђ→ђ, Ј→ј, Љ→љ, Њ→њ, Ћ→ћ, Џ→џ, …)
        '\u{0400}'..='\u{040F}' => char::from_u32(c as u32 + 0x50).unwrap_or(c),
        other => other,
    }
}

/// Normalize a whole string character-by-character. Every mapping is
/// single-char to single-char, so folding commutes with prefixing.
pub fn fold_str(s: &str) -> String {
    s.chars().map(fold_char).collect()
}

/// Whether `c` is a token character for the generated alphabet:
/// alphanumeric in any script. Everything else (ASCII whitespace and
/// punctuation, NBSP) separates tokens.
fn is_token_char(c: char) -> bool {
    if c == '\u{00A0}' {
        return false; // unicode61 treats NBSP as a separator
    }
    c.is_ascii_alphanumeric() || (c as u32) >= 0x80
}

/// Tokenize exactly as `unicode61` does: maximal runs of token characters,
/// each folded to lowercase/base form.
pub fn tokenize(text: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut cur = String::new();
    for c in text.chars() {
        if is_token_char(c) {
            cur.push(fold_char(c));
        } else if !cur.is_empty() {
            out.push(std::mem::take(&mut cur));
        }
    }
    if !cur.is_empty() {
        out.push(cur);
    }
    out
}

/// Whether a term query on `term` matches `msg` (searching `body` and
/// `author` columns).
pub fn term_matches(msg: &NewMessage, term: &str) -> bool {
    let folded = fold_str(term);
    tokenize(&msg.body).contains(&folded) || tokenize(&msg.author).contains(&folded)
}

/// Whether a prefix query `term*` matches `msg`.
pub fn prefix_matches(msg: &NewMessage, prefix: &str) -> bool {
    let folded = fold_str(prefix);
    tokenize(&msg.body)
        .iter()
        .chain(tokenize(&msg.author).iter())
        .any(|token| token.starts_with(&folded))
}

/// Whether a phrase query `"a b"` matches `msg`. Tokens must be adjacent
/// *within one column*; body and author are separate FTS columns, so a
/// phrase never spans the body→author boundary.
pub fn phrase_matches(msg: &NewMessage, a: &str, b: &str) -> bool {
    let fa = fold_str(a);
    let fb = fold_str(b);
    [tokenize(&msg.body), tokenize(&msg.author)]
        .iter()
        .any(|tokens| tokens.windows(2).any(|pair| pair[0] == fa && pair[1] == fb))
}

